from src.processing import filter_by_state, sort_by_date
import pytest


@pytest.fixture
def list_dict():
    return [
        {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
        {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
        {"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"},
        {"id": 615064591, "state": "CANCELED", "date": "2018-10-14T08:21:33.419441"},
    ]


@pytest.fixture
def value_canceled_list_dict():
    return [
        {"id": 594226727, "state": "CANCELED", "date": "2018-09-12T21:27:25.241689"},
        {"id": 615064591, "state": "CANCELED", "date": "2018-10-14T08:21:33.419441"},
    ]


@pytest.fixture
def value_executed_list_dict():
    return [
        {"id": 41428829, "state": "EXECUTED", "date": "2019-07-03T18:35:29.512364"},
        {"id": 939719570, "state": "EXECUTED", "date": "2018-06-30T02:08:58.425572"},
    ]


def test_filter_by_state(list_dict, value_canceled_list_dict, value_executed_list_dict):
    assert filter_by_state(list_dict, "CANCELED") == value_canceled_list_dict
    assert filter_by_state(list_dict, "EXECUTED") == value_executed_list_dict


def test_empty_filter_by_state(list_dict, value_canceled_list_dict, value_executed_list_dict):
    assert filter_by_state(list_dict, "") == []


